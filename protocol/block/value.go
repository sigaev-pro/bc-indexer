// parseFixed decodes n bytes from hex text, with or without a 0x prefix.
func parseFixed(text []byte, n int) ([]byte, error) {
	s := string(text)
	s = strings.TrimPrefix(strings.TrimPrefix(s, "0x"), "0X")
	if len(s) != 2*n {
		return nil, fmt.Errorf("%w: %d-byte hex value has %d hex digits", ErrInvalidValue, n, len(s))
	}
	b, err := hex.DecodeString(s)
	if err != nil {
		return nil, fmt.Errorf("%w: hex: %v", ErrInvalidValue, err)
	}
	return b, nil
}

// Optional is a presence-explicit optional field. The zero Optional is
// absent; a present zero value of T stays a present value. The schema never
// substitutes a zero value for absence or the other way around.
type Optional[T any] struct {
	present bool
	value   T
}

// Some returns v as a present optional.
func Some[T any](v T) Optional[T] { return Optional[T]{present: true, value: v} }

// None returns the absent optional of T.
func None[T any]() Optional[T] { return Optional[T]{} }

// Present reports whether a value is present.
func (o Optional[T]) Present() bool { return o.present }

// Get returns the value and whether it is present. When o is absent, the
// returned value is the zero value of T and must not be used as data.
func (o Optional[T]) Get() (T, bool) { return o.value, o.present }

// MustGet returns the value and panics when o is absent. It is for closed
// fixtures and tests that already checked presence.
func (o Optional[T]) MustGet() T {
	if !o.present {
		panic("block: absent optional")
	}
	return o.value
}

// Equal reports whether both optionals have equal presence and value.
func (o Optional[T]) Equal(other Optional[T]) bool {
	if o.present != other.present {
		return false
	}
	if !o.present {
		return true
	}
	return anyEqual(o.value, other.value)
}

// String renders the optional for diagnostics: "<absent>" or the value.
func (o Optional[T]) String() string {
	if !o.present {
		return "<absent>"
	}
	return fmt.Sprintf("%v", o.value)
}

// MarshalJSON encodes absent as null and present as the value itself, so a
// present zero stays distinguishable from absence in the local encoding.
func (o Optional[T]) MarshalJSON() ([]byte, error) {
	if !o.present {
		return []byte("null"), nil
	}
	return jsonMarshal(o.value)
}

// UnmarshalJSON decodes null as absent and anything else as present.
func (o *Optional[T]) UnmarshalJSON(data []byte) error {
	if string(data) == "null" {
		o.present = false
		var zero T
		o.value = zero
		return nil
	}
	var v T
	if err := jsonUnmarshal(data, &v); err != nil {
		return err
	}
	o.present = true
	o.value = v
	return nil
}

// Timestamp preserves the source precision of a block reference. ETH and Bor
// observe whole seconds (nanos 0, precision SECONDS). BSC derives
// MilliTimestamp() with checked arithmetic: seconds=ms/1000,
// nanos=(ms%1000)*1e6, precision MILLISECONDS. The raw header time and mix
// digest stay unchanged in the header.
type Timestamp struct {
	Seconds   uint64    `json:"seconds"`
	Nanos     uint32    `json:"nanos"`
	Precision Precision `json:"precision"`
}

// TimestampFromSeconds builds the ETH and Bor form: the native header time
// in whole seconds, precision SECONDS.
func TimestampFromSeconds(seconds uint64) Timestamp {
	return Timestamp{Seconds: seconds, Nanos: 0, Precision: PrecisionSeconds}
}

// TimestampFromMilliseconds builds the BSC form from the native
// MilliTimestamp() with checked arithmetic: seconds=ms/1000,
// nanos=(ms%1000)*1e6, precision MILLISECONDS. The remainder stays below
// one second, which uint32 nanoseconds always hold.
func TimestampFromMilliseconds(ms uint64) Timestamp {
	return Timestamp{
		Seconds:   ms / 1000,
		Nanos:     uint32((ms % 1000) * 1_000_000),
		Precision: PrecisionMilliseconds,
	}
}

// Precision names the source precision actually preserved.
type Precision uint8

// Precisions. Zero is not a valid precision.
const (
	PrecisionSeconds Precision = iota + 1
	PrecisionMilliseconds
	PrecisionNanoseconds
)

var precisionNames = []string{"SECONDS", "MILLISECONDS", "NANOSECONDS"}

// String returns the contract name of p.
func (p Precision) String() string {
	if p == 0 || int(p) > len(precisionNames) {
		return "INVALID"
	}
	return precisionNames[p-1]
}

// Validate checks the precision and the nano-second consistency rules of the
// family timestamp derivations.
func (t Timestamp) Validate() error {
	if t.Precision == 0 || int(t.Precision) > len(precisionNames) {
		return fmt.Errorf("%w: timestamp precision %d", ErrInvalidValue, uint8(t.Precision))
	}
	if t.Nanos >= 1_000_000_000 {
		return fmt.Errorf("%w: timestamp nanos %d", ErrInvalidValue, t.Nanos)
	}
	switch t.Precision {
	case PrecisionSeconds:
		if t.Nanos != 0 {
			return fmt.Errorf("%w: SECONDS timestamp with nanos %d", ErrInvalidValue, t.Nanos)
		}
	case PrecisionMilliseconds:
		if t.Nanos%1_000_000 != 0 {
			return fmt.Errorf("%w: MILLISECONDS timestamp nanos %d not a whole millisecond", ErrInvalidValue, t.Nanos)
		}
	case PrecisionNanoseconds:
	}
	return nil
}

// MarshalJSON encodes the timestamp with the precision as its contract name.
func (t Timestamp) MarshalJSON() ([]byte, error) {
	if err := t.Validate(); err != nil {
		return nil, err
	}
	type timestampJSON struct {
		Seconds   uint64 `json:"seconds"`
		Nanos     uint32 `json:"nanos"`
		Precision string `json:"precision"`
	}
	return jsonMarshal(timestampJSON{t.Seconds, t.Nanos, t.Precision.String()})
}

// UnmarshalJSON decodes the precision name strictly.
func (t *Timestamp) UnmarshalJSON(data []byte) error {
	type timestampJSON struct {
		Seconds   uint64 `json:"seconds"`
		Nanos     uint32 `json:"nanos"`
		Precision string `json:"precision"`
	}
	var v timestampJSON
	if err := jsonUnmarshal(data, &v); err != nil {
		return err
	}
	p, err := precisionByName(v.Precision)
	if err != nil {
		return err
	}
	t.Seconds, t.Nanos, t.Precision = v.Seconds, v.Nanos, p
	return nil
}

func precisionByName(name string) (Precision, error) {
	for i, n := range precisionNames {
		if n == name {
			return Precision(i + 1), nil
		}
	}
	return 0, fmt.Errorf("%w: unknown timestamp precision %q", ErrInvalidValue, name)
}

// NetworkIdentity identifies the network of a record: the single EVM family,
// the chain id and the genesis hash. The genesis hash is the real source
// hash; the all-zero hash never encodes a known genesis.
type NetworkIdentity struct {
	Family      string  `json:"family"`
	ChainID     UInt256 `json:"chain_id"`
	GenesisHash Hash32  `json:"genesis_hash"`
}

// Validate checks the closed family and the non-zero identities.
func (n NetworkIdentity) Validate() error {
	if n.Family != evmFamily {
		return fmt.Errorf("%w: network family %q", ErrInvalidValue, n.Family)
	}
	if n.ChainID.IsZero() {
		return fmt.Errorf("%w: network chain id is zero", ErrInvalidValue)
	}
	if n.GenesisHash.IsZero() {
		return fmt.Errorf("%w: network genesis hash is zero", ErrInvalidValue)
	}
	return nil
}

// AnchorRef is a native anchor: a height and its block hash. Projection and
// ancestry use the exact hash, never the height alone.
type AnchorRef struct {
	Height uint64 `json:"height"`
	Hash   Hash32 `json:"hash"`
}

// Validate requires a non-zero hash: a known anchor always has a source
// hash, and zero hashes stay native no-ops or unset references.
func (a AnchorRef) Validate() error {
	if a.Hash.IsZero() {
		return fmt.Errorf("%w: anchor at height %d has zero hash", ErrInvalidValue, a.Height)
	}
	return nil
}
