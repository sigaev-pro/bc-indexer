// ErrInvalidValue reports a value that violates a fixed-width or closed-enum
// rule of the schema. It is returned before any record is considered READY.
var ErrInvalidValue = errors.New("block: invalid value")

// Family is the closed client family of a network profile.
type Family string

// Families. The public Envelope NetworkIdentity family stays EVM; Family
// distinguishes which closed fork context applies to a block record.
const (
	FamilyEth  Family = "ETH"
	FamilyBsc  Family = "BSC"
	FamilyPoly Family = "POLY"
)

// Valid reports whether f is one of the closed families.
func (f Family) Valid() bool {
	switch f {
	case FamilyEth, FamilyBsc, FamilyPoly:
		return true
	default:
		return false
	}
}

// evmFamily is the single Envelope network family of the current contract.
const evmFamily = "EVM"

// Hash32 is a 32-byte native hash. Text form is 64 lowercase hex digits with
// no 0x prefix (CONTROL_WIRE_CONTRACT).
type Hash32 [32]byte

// IsZero reports whether h is the all-zero hash. The all-zero hash never
// encodes a known genesis or a known anchor: a real genesis has a source
// hash, and zero hashes are native no-ops or unset references.
func (h Hash32) IsZero() bool { return h == Hash32{} }

// String returns the 64 lowercase hex digits of h.
func (h Hash32) String() string { return hex.EncodeToString(h[:]) }

// MarshalText encodes h as 64 lowercase hex digits.
func (h Hash32) MarshalText() ([]byte, error) { return []byte(h.String()), nil }

// UnmarshalText decodes exactly 32 bytes from hex, with or without a 0x
// prefix. Any other length is ErrInvalidValue.
func (h *Hash32) UnmarshalText(text []byte) error {
	v, err := parseFixed(text, 32)
	if err != nil {
		return err
	}
	copy(h[:], v)
	return nil
}

